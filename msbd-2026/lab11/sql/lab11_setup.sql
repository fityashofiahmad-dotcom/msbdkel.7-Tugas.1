-- Deterministik: dijalankan berulang menghasilkan data yang sama.
-- Hasil akhir: tenant=3, pelanggan=30000, akun=4, transaksi=120000.
-- Sengaja BELUM ada RLS dan BELUM ada kebijakan (itu dikerjakan di Q6-Q7).
