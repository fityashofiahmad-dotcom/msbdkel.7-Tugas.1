\set ON_ERROR_STOP on
\echo '== Membersihkan sisa percobaan sebelumnya =='

DROP SCHEMA IF EXISTS lab11 CASCADE;

DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['app_auditor','app_analitik','app_portal','app_laporan',
                           'app_write','app_read','skema_owner'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('DROP OWNED BY %I', r);
      EXECUTE format('DROP ROLE %I', r);
    END IF;
  END LOOP;
END $$;

\echo '== Membuat tujuh peran =='
-- Lapis 1: pemilik (tidak pernah login)
CREATE ROLE skema_owner NOLOGIN;
-- Lapis 2: peran fungsional (kumpulan hak, tidak login)
CREATE ROLE app_read    NOLOGIN;
CREATE ROLE app_write   NOLOGIN;
-- Lapis 3: peran login (meminjam hak dari lapis 2)
CREATE ROLE app_laporan  LOGIN PASSWORD 'lab11_laporan'  IN ROLE app_read;
CREATE ROLE app_portal   LOGIN PASSWORD 'lab11_portal'   IN ROLE app_write;
-- Peran login lain, tanpa keanggotaan (hak diberikan sendiri-sendiri)
CREATE ROLE app_analitik LOGIN PASSWORD 'lab11_analitik';
CREATE ROLE app_auditor  LOGIN PASSWORD 'lab11_auditor';

\echo '== Membuat skema dan hak bawaan =='
CREATE SCHEMA lab11 AUTHORIZATION skema_owner;
GRANT USAGE ON SCHEMA lab11 TO app_read, app_write, app_analitik, app_auditor;

-- Tabel baru buatan skema_owner otomatis bisa dibaca app_read (dipakai di Q3).
-- Sengaja hanya untuk skema_owner; tabel buatan postgres TIDAK ikut (jawaban Q3).
ALTER DEFAULT PRIVILEGES FOR ROLE skema_owner IN SCHEMA lab11
  GRANT SELECT ON TABLES TO app_read;

\echo '== Membuat tabel (dimiliki skema_owner) =='
SET ROLE skema_owner;

CREATE TABLE lab11.tenant (
  id    int  PRIMARY KEY,
  nama  text NOT NULL
);

CREATE TABLE lab11.pelanggan (
  id          int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   int         NOT NULL REFERENCES lab11.tenant(id),
  nama        text        NOT NULL,
  nik         text        NOT NULL,
  surel       text        NOT NULL,
  lahir       date        NOT NULL,
  kota        text        NOT NULL,
  saldo       numeric(14,2) NOT NULL,
  status      text        NOT NULL DEFAULT 'AKTIF',
  dibuat_pada timestamptz NOT NULL
);
CREATE INDEX pelanggan_tenant_idx ON lab11.pelanggan (tenant_id);

CREATE TABLE lab11.akun (
  id               int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_pengguna    text NOT NULL UNIQUE,
  peran_aplikasi   text NOT NULL,
  kata_sandi_hash  text NOT NULL
);

CREATE TABLE lab11.transaksi (
  id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pelanggan_id int         NOT NULL REFERENCES lab11.pelanggan(id),
  tenant_id    int         NOT NULL REFERENCES lab11.tenant(id),
  jumlah       numeric(14,2) NOT NULL,
  jenis        text        NOT NULL,
  dibuat_pada  timestamptz NOT NULL
);
CREATE INDEX transaksi_pelanggan_idx ON lab11.transaksi (pelanggan_id);

