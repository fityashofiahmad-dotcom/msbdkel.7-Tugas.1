SELECT setval(pg_get_serial_sequence('lab11.transaksi','id'), (SELECT max(id) FROM lab11.transaksi));

RESET ROLE;

\echo '== Memberi hak per peran =='
-- app_read sudah dapat SELECT semua tabel lewat default privileges di atas.
-- app_write: baca + ubah data pelanggan dan transaksi (tidak boleh menyentuh akun).
GRANT SELECT ON lab11.tenant, lab11.pelanggan, lab11.transaksi TO app_write;
GRANT INSERT, UPDATE, DELETE ON lab11.pelanggan, lab11.transaksi TO app_write;
-- app_auditor: hanya membaca akun dan transaksi.
GRANT SELECT ON lab11.akun, lab11.transaksi TO app_auditor;
